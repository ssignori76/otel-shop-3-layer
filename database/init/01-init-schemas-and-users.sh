#!/bin/sh
set -eu

mysql -u root -p"${MYSQL_ROOT_PASSWORD}" <<-EOSQL
    CREATE DATABASE IF NOT EXISTS auth_db CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
    CREATE DATABASE IF NOT EXISTS cart_db CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
    CREATE DATABASE IF NOT EXISTS checkout_db CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
    CREATE DATABASE IF NOT EXISTS fulfillment_db CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;

    CREATE USER IF NOT EXISTS '${MYSQL_AUTH_USER:-auth_app}'@'%' IDENTIFIED BY '${MYSQL_AUTH_PASSWORD:-auth_local_dev_only}';
    GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES ON auth_db.* TO '${MYSQL_AUTH_USER:-auth_app}'@'%';

    CREATE USER IF NOT EXISTS '${MYSQL_CART_USER}'@'%' IDENTIFIED BY '${MYSQL_CART_PASSWORD}';
    GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES ON cart_db.* TO '${MYSQL_CART_USER}'@'%';

    CREATE USER IF NOT EXISTS '${MYSQL_CHECKOUT_USER}'@'%' IDENTIFIED BY '${MYSQL_CHECKOUT_PASSWORD}';
    GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES ON checkout_db.* TO '${MYSQL_CHECKOUT_USER}'@'%';

    CREATE USER IF NOT EXISTS '${MYSQL_FULFILLMENT_USER}'@'%' IDENTIFIED BY '${MYSQL_FULFILLMENT_PASSWORD}';
    GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES ON fulfillment_db.* TO '${MYSQL_FULFILLMENT_USER}'@'%';

    FLUSH PRIVILEGES;
EOSQL
